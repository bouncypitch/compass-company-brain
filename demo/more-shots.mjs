import { launch, login, BASE } from './lib.mjs';
const { browser, page } = await launch();
await login(page);
await page.goto(`${BASE}/brain`);
await page.waitForURL(/\/brain$/);
await page.getByText('Competitive landscape').waitFor({ timeout: 20000 });
await page.getByRole('button', { name: 'Time machine' }).click();
await page.getByText('What actually happened').waitFor({ timeout: 20000 });
await page.getByText('What actually happened').scrollIntoViewIfNeeded();
await page.waitForTimeout(600);
await page.screenshot({ path: 'checkpoints/09-time-machine.png' });
await page.getByRole('tab', { name: 'Compass' }).click();
await page.getByText('Where you stand').waitFor({ timeout: 30000 });
await page.waitForTimeout(600);
await page.screenshot({ path: 'checkpoints/10-compass-top.png' });
await page.getByText('Your best promotion bets').scrollIntoViewIfNeeded();
await page.waitForTimeout(500);
await page.screenshot({ path: 'checkpoints/11-compass-bets.png' });
await page.getByRole('tab', { name: 'Story' }).click();
await page.waitForTimeout(3000);
await page.screenshot({ path: 'checkpoints/12-story.png' });
await browser.close();
console.log('ok');
